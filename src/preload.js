const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('aura', {
  getState: () => ipcRenderer.invoke('browser:get-state'),
  createTab: (url) => ipcRenderer.invoke('browser:create-tab', url),
  selectTab: (id) => ipcRenderer.invoke('browser:select-tab', id),
  closeTab: (id) => ipcRenderer.invoke('browser:close-tab', id),
  reorderTabs: (fromId, toId) => ipcRenderer.invoke('browser:reorder-tabs', fromId, toId),
  toggleBookmark: () => ipcRenderer.invoke('browser:toggle-bookmark'),
  removeBookmark: (id) => ipcRenderer.invoke('browser:remove-bookmark', id),
  importBookmarks: (source) => ipcRenderer.invoke('browser:import-bookmarks', source),
  importProfile: (browser) => ipcRenderer.invoke('browser:import-profile', browser),
  importPasswordCsv: () => ipcRenderer.invoke('browser:import-password-csv'),
  getImportedData: () => ipcRenderer.invoke('browser:get-imported-data'),
  getPasswords: () => ipcRenderer.invoke('browser:get-passwords'),
  passwordVaultStatus: () => ipcRenderer.invoke('browser:password-vault-status'),
  unlockPasswordVault: () => ipcRenderer.invoke('browser:unlock-password-vault'),
  lockPasswordVault: () => ipcRenderer.invoke('browser:lock-password-vault'),
  removeSitePermission: (origin, name) => ipcRenderer.invoke('browser:remove-site-permission', origin, name),
  resetSitePermissions: () => ipcRenderer.invoke('browser:reset-site-permissions'),
  removeImportedItem: (collection, id) => ipcRenderer.invoke('browser:remove-imported-item', collection, id),
  clearHistory: () => ipcRenderer.invoke('browser:clear-history'),
  navigate: (url) => ipcRenderer.invoke('browser:navigate', url),
  goBack: () => ipcRenderer.invoke('browser:back'),
  goForward: () => ipcRenderer.invoke('browser:forward'),
  reload: () => ipcRenderer.invoke('browser:reload'),
  setStageBounds: (bounds) => ipcRenderer.send('browser:set-stage-bounds', bounds),
  setSplit: (mode, ratio, tabId) => ipcRenderer.invoke('browser:set-split', mode, ratio, tabId),
  toggleSettings: () => ipcRenderer.invoke('browser:toggle-settings'),
  closeSettings: () => ipcRenderer.invoke('browser:close-settings'),
  completeSetup: (preferences) => ipcRenderer.invoke('browser:complete-setup', preferences),
  chooseDownloadDirectory: () => ipcRenderer.invoke('browser:choose-download-directory'),
  downloadAction: (id, action) => ipcRenderer.invoke('browser:download-action', id, action),
  clearSiteData: () => ipcRenderer.invoke('browser:clear-site-data'),
  openDevTools: () => ipcRenderer.invoke('browser:open-devtools'),
  findText: (text, direction, newSearch) => ipcRenderer.invoke('browser:find-text', text, direction, newSearch),
  stopFind: () => ipcRenderer.invoke('browser:stop-find'),
  beginTabDrag: (id) => ipcRenderer.send('browser:begin-tab-drag', id),
  endTabDrag: () => ipcRenderer.send('browser:end-tab-drag'),
  openGlance: (url) => ipcRenderer.invoke('browser:open-glance', url),
  updatePreferences: (preferences) => ipcRenderer.invoke('browser:update-preferences', preferences),
  setShortcutCapture: (enabled) => ipcRenderer.send('browser:set-shortcut-capture', Boolean(enabled)),
  toggleTor: () => ipcRenderer.invoke('browser:toggle-tor'),
  aliasesStatus: () => ipcRenderer.invoke('aliases:status'),
  copyText: (text) => ipcRenderer.invoke('aliases:copy', text),
  aliasesConnect: (apiKey) => ipcRenderer.invoke('aliases:connect', apiKey),
  aliasesList: (page) => ipcRenderer.invoke('aliases:list', page),
  aliasesCreate: (note) => ipcRenderer.invoke('aliases:create', note),
  aliasesUpdateNote: (id, note) => ipcRenderer.invoke('aliases:update-note', id, note),
  aliasesToggle: (id) => ipcRenderer.invoke('aliases:toggle', id),
  aliasesDelete: (id) => ipcRenderer.invoke('aliases:delete', id),
  aliasesDisconnect: () => ipcRenderer.invoke('aliases:disconnect'),
  minimize: () => ipcRenderer.send('window:minimize'),
  toggleMaximize: () => ipcRenderer.send('window:toggle-maximize'),
  closeWindow: () => ipcRenderer.send('window:close'),
  onState: (callback) => { ipcRenderer.on('browser:state', (_event, state) => callback(state)); },
  onToast: (callback) => { ipcRenderer.on('browser:toast', (_event, message) => callback(message)); },
  onFindResult: (callback) => { ipcRenderer.on('browser:find-result', (_event, result) => callback(result)); },
  onCommand: (callback) => { ipcRenderer.on('browser:command', (_event, command) => callback(command)); }
});